/// Chain of thought for the agents — built as a REAL extra inference
/// pass, not a cosmetic "thinking…" spinner.
///
/// Before speaking, the agent runs a dedicated THINK step: a
/// separate inference call whose only job is structured reasoning,
/// returned as JSON with fixed fields (situation, feeling, memory,
/// goal, options, chosen, why). That JSON is the agent's working
/// chain of thought for the turn:
///  - it is fed into the reply prompt, so the reply actually follows
///    from the reasoning;
///  - a short summary of it (situation → chosen → why) is shown in
///    the UI as the agent's thought line — "show the work", per
///    Dan's operator card. The full JSON is kept on the turn object.
///
/// HONESTY: the think step is generated by the same model that
/// writes the reply; it is a structured reasoning step, not a
/// window into hidden model internals, and it is labelled that way
/// in docs/CHARACTER_AI.md. If the think call fails or returns
/// unparseable JSON, the turn proceeds WITHOUT a thought and the
/// trace records that — no thought is ever invented for display.
class ThoughtStep {
  const ThoughtStep({
    required this.situation,
    required this.feeling,
    required this.memory,
    required this.goal,
    required this.options,
    required this.chosen,
    required this.why,
  });

  final String situation;
  final String feeling;
  final String memory;
  final String goal;
  final List<String> options;
  final String chosen;
  final String why;

  String get summary => '$situation → chose: $chosen — $why';

  Map<String, dynamic> toJson() => {
        'situation': situation,
        'feeling': feeling,
        'memory': memory,
        'goal': goal,
        'options': options,
        'chosen': chosen,
        'why': why,
      };

  /// Strict-ish parse: returns null on any missing core field so a
  /// malformed think step degrades honestly instead of half-parsing.
  static ThoughtStep? tryParse(String raw) {
    try {
      final start = raw.indexOf('{');
      final end = raw.lastIndexOf('}');
      if (start < 0 || end <= start) return null;
      final doc = jsonDecode(raw.substring(start, end + 1))
          as Map<String, dynamic>;
      String req(String k) {
        final v = doc[k];
        if (v is! String || v.trim().isEmpty) {
          throw const FormatException('missing field');
        }
        return v.trim();
      }

      final opts = doc['options'];
      return ThoughtStep(
        situation: req('situation'),
        feeling: req('feeling'),
        memory: req('memory'),
        goal: req('goal'),
        options: opts is List
            ? opts.map((e) => e.toString()).toList()
            : const [],
        chosen: req('chosen'),
        why: req('why'),
      );
    } catch (_) {
      return null;
    }
  }
}

class Thinker {
  Thinker({InferenceRouter? router})
      : router = router ?? InferenceRouter.shared;
  final InferenceRouter router;

  /// Run the think step for [agentName]'s next move. Returns null
  /// when the step could not be produced/parsed — callers continue
  /// without it and must not display a thought they didn't get.
  Future<ThoughtStep?> think({
    required CharacterDef def,
    required AffectState affect,
    required AgentSelf self,
    required Map<String, String> namesById,
    required TimeContext time,
    required String context,
    required String stimulus,
  }) async {
    final prompt = [
      'You are the inner reasoning of ${def.displayName} '
          '(${def.title}) in Rich Gang AI. Think step by step, '
          'privately, before ${def.name} speaks.',
      'WHO YOU ARE: ${self.promptBlock(namesById)}',
      'HOW YOU FEEL: ${affect.moodLine()}',
      'TIME: ${time.promptBlock()}',
      'CONTEXT: $context',
      'STIMULUS: $stimulus',
      'Reply with ONLY a JSON object, no other text, with fields: '
          '"situation" (what is happening, one line), "feeling" '
          '(what you feel about it and why), "memory" (the relevant '
          'thing you recall, or "none"), "goal" (what you want from '
          'your next line), "options" (array of 2-3 moves you could '
          'make), "chosen" (the move you pick), "why" (one line).',
    ].join('\n');
    try {
      final raw = await router.run(InferenceTask.personaDialogue, prompt);
      return ThoughtStep.tryParse(raw);
    } catch (_) {
      return null;
    }
  }
}

/// Deep reasoning: draft → critique → revise, three real inference
/// passes, for hard questions. The final answer is the revision; the
/// critique is kept so the UI can show how the answer improved.
/// Costs ~3× a normal reply in time and calls — the UI labels it
/// as the slow, thorough mode, and any failed pass aborts with the
/// error instead of returning a half-deepened draft as if it were
/// the deep answer.
class DeepReasoner {
  DeepReasoner({InferenceRouter? router})
      : router = router ?? InferenceRouter.shared;
  final InferenceRouter router;

  Future<DeepAnswer> reason({
    required String systemPrompt,
    required String question,
  }) async {
    final draft = await router.run(
      InferenceTask.personaDialogue,
      '$systemPrompt\n\nQUESTION: $question\n\nGive your best '
          'first answer, thinking it through step by step before '
          'concluding.',
    );
    final critique = await router.run(
      InferenceTask.personaDialogue,
      'You are the critical inner voice of the same agent. Read '
          'this draft answer to "$question" and list its specific '
          'weaknesses: wrong or missing facts, weak logic, hedging, '
          'anything off-character. Be concrete and brief.\n\n'
          'DRAFT:\n$draft',
    );
    final revised = await router.run(
      InferenceTask.personaDialogue,
      '$systemPrompt\n\nQUESTION: $question\n\nYour first draft '
          'was:\n$draft\n\nYour own critique of it was:\n$critique\n\n'
          'Now give the final answer, fixing every valid criticism. '
          'Speak only the final answer, in character.',
    );
    return DeepAnswer(draft: draft, critique: critique, answer: revised);
  }
}

class DeepAnswer {
  const DeepAnswer({
    required this.draft,
    required this.critique,
    required this.answer,
  });
  final String draft;
  final String critique;
  final String answer;
}
